// Перевод категории
export const translateCategory = (category?: string): string => {
  if (!category) return '';
  return categoryTranslations[category.toLowerCase()] || category;
};

// Перевод ингредиента
export const translateIngredient = (ingredient?: string): string => {
  if (!ingredient) return '';
  const lower = ingredient.toLowerCase();
  return ingredientTranslations[lower] || ingredient;
};

// Перевод единицы измерения
export const translateUnit = (unit?: string): string => {
  if (!unit) return '';
  return unitTranslations[unit.toLowerCase()] || unit;
};

// Перевод сложности
export const translateDifficulty = (difficulty?: string): string => {
  if (!difficulty) return '';
  const map: Record<string, string> = {
    'easy': '🥚 Легко',
    'medium': '👨‍🍳 Средне',
    'hard': '🔥 Сложно',
  };
  return map[difficulty.toLowerCase()] || difficulty;
};

// Форматирование времени
export const formatTime = (minutes?: number): string => {
  if (!minutes) return '';
  if (minutes < 60) return `${minutes} мин`;
  const hours = Math.floor(minutes / 60);
  const mins = minutes % 60;
  return mins > 0 ? `${hours} ч ${mins} мин` : `${hours} ч`;
};